public class Pair {
    int left; int right;

    public Pair(int left, int right) {
        this.left = left;
        this.right = right;
    }

    public int left() {
        return left;
    }

    public void setLeft(int left) {
        this.left = left;
    }

    public int right() {
        return right;
    }

    public void setRight(int right) {
        this.right = right;
    }
}
